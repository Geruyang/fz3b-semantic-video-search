"""Export the locked research S1 image encoder and validate against PyTorch.

Text features are generated by the same locked model. The ONNX artifact has its
own manifest; it is not presented as the original PyTorch cache identity.
"""
import argparse
from collections import Counter
import json
from pathlib import Path
import time

import numpy as np
import onnx
import onnxruntime as ort
import torch

from desktop_vlm.cache import sha256_file
from desktop_vlm.matching import normalize_rows
from desktop_vlm.model import MobileCLIPEncoder
from desktop_vlm.prompts import load_prompts


class ImageEncoder(torch.nn.Module):
    def __init__(self, model):
        super().__init__()
        self.model = model

    def forward(self, image):
        return self.model.encode_image(image)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--official-repo', required=True)
    parser.add_argument('--weights', required=True)
    parser.add_argument('--prompts', required=True)
    parser.add_argument('--image', action='append', required=True)
    parser.add_argument('--output', required=True)
    args = parser.parse_args()
    output = Path(args.output)
    output.mkdir(parents=True, exist_ok=False)
    encoder = MobileCLIPEncoder(official_repo=args.official_repo, weights=args.weights)
    prompts = load_prompts(args.prompts)
    text = normalize_rows(encoder.encode_texts([p['text'] for p in prompts]))
    np.asarray(text, dtype='<f4').tofile(output / 'text-features.f32')
    images = [encoder.preprocess_image(path).unsqueeze(0) for path in args.image]
    model_path = output / 'mobileclip_s1_image.onnx'
    wrapper = ImageEncoder(encoder.model).eval()
    with torch.inference_mode():
        torch.onnx.export(wrapper, images[0], str(model_path), input_names=['image'],
                          output_names=['features'], opset_version=17,
                          dynamo=False, do_constant_folding=True)
    graph = onnx.load(str(model_path))
    onnx.checker.check_model(graph)
    options = ort.SessionOptions()
    options.intra_op_num_threads = 4
    options.inter_op_num_threads = 1
    ort.disable_telemetry_events()
    session = ort.InferenceSession(str(model_path), sess_options=options,
                                   providers=['CPUExecutionProvider'])
    results = []
    for index, (source, tensor) in enumerate(zip(args.image, images)):
        prefix = 'image-%02d' % index
        array = tensor.numpy().astype('<f4')
        array.tofile(output / (prefix + '-input.f32'))
        with torch.inference_mode():
            expected = wrapper(tensor).numpy()
        expected.astype('<f4').tofile(output / (prefix + '-torch.f32'))
        start = time.perf_counter()
        actual = session.run(['features'], {'image': array})[0]
        elapsed = (time.perf_counter() - start) * 1000
        actual.astype('<f4').tofile(output / (prefix + '-ort.f32'))
        np.testing.assert_allclose(actual, expected, rtol=1e-3, atol=1e-4)
        expected_scores = normalize_rows(expected) @ text.T
        actual_scores = normalize_rows(actual) @ text.T
        np.testing.assert_allclose(actual_scores, expected_scores, rtol=0, atol=1e-5)
        order = np.argsort(-actual_scores[0], kind='stable')
        results.append({'prefix': prefix, 'source': str(Path(source).resolve()),
                        'source_sha256': sha256_file(source),
                        'feature_max_abs': float(np.max(np.abs(actual - expected))),
                        'score_max_abs': float(np.max(np.abs(actual_scores - expected_scores))),
                        'ort_single_run_ms': elapsed,
                        'scores': actual_scores[0].tolist(),
                        'ranking': [prompts[int(i)]['id'] for i in order]})
    manifest = {'schema_version': 1, 'purpose': 'research-board-validation',
                'source_identity': encoder.identity(), 'runtime': {'onnx': onnx.__version__,
                'onnxruntime': ort.__version__, 'torch': torch.__version__},
                'input': {'name': 'image', 'shape': [1, 3, 256, 256], 'dtype': 'little-endian-float32'},
                'output': {'name': 'features', 'shape': [1, 512], 'normalization': 'raw'},
                'text_features': {'file': 'text-features.f32', 'shape': list(text.shape), 'normalization': 'l2'},
                'prompts': prompts, 'onnx_ir_version': graph.ir_version,
                'opsets': {entry.domain: entry.version for entry in graph.opset_import},
                'operators': dict(Counter(node.op_type for node in graph.graph.node)),
                'validation': results,
                'files': {p.name: {'size': p.stat().st_size, 'sha256': sha256_file(p)}
                          for p in output.iterdir() if p.is_file()}}
    (output / 'manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding='utf-8')
    print(json.dumps({'status': 'PASS', 'output': str(output.resolve()),
                      'ir_version': graph.ir_version, 'validation': results}, ensure_ascii=False))


if __name__ == '__main__':
    main()
